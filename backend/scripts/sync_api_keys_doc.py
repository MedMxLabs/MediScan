#!/usr/bin/env python3
"""Fill docs/API_KEYS.local.md from backend/.env and frontend/.env (gitignored)."""
from __future__ import annotations

from datetime import date
from pathlib import Path

_BACKEND = Path(__file__).resolve().parent.parent
_REPO = _BACKEND.parent
_DOC = _REPO / "docs" / "API_KEYS.local.md"


def _parse_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.is_file():
        return out
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        out[k.strip()] = v.strip()
    return out


def _row(key: str, val: str) -> str:
    return f"| `{key}` | {val or '_(not set)_'} |"


def main() -> int:
    be = _parse_env(_BACKEND / ".env")
    be.update(_parse_env(_REPO / ".env"))
    fe = _parse_env(_REPO / "frontend" / ".env")

    client = be.get("MEDSCAN_CLIENT_API_KEYS") or be.get("MEDSCAN_CLIENT_API_KEY", "")

    backend_keys = [
        "SUPABASE_URL",
        "SUPABASE_ANON_KEY",
        "SUPABASE_JWT_SECRET",
        "SECRET_KEY",
        "JWT_SECRET_KEY",
        "DATABASE_URL",
        "MEDSCAN_CLIENT_API_KEYS",
        "AZURE_OPENAI_API_BASE",
        "AZURE_OPENAI_API_KEY",
        "AZURE_OPENAI_MODEL",
        "AZURE_OPENAI_API_VERSION",
        "MEDSCAN_AI_MEDICINE_FALLBACK",
        "AZURE_DOCUMENT_INTELLIGENCE_ENDPOINT",
        "AZURE_DOCUMENT_INTELLIGENCE_KEY",
        "CORS_ORIGINS",
    ]
    frontend_keys = [
        "VITE_API_URL",
        "VITE_SUPABASE_URL",
        "VITE_SUPABASE_ANON_KEY",
        "VITE_MEDSCAN_API_KEY",
        "VITE_OMNIDIMENSION_WIDGET_SECRET",
    ]
    azure_keys = [
        "MEDSCAN_CLIENT_API_KEYS",
        "AZURE_OPENAI_API_KEY",
        "AZURE_OPENAI_API_BASE",
        "SECRET_KEY",
        "JWT_SECRET_KEY",
        "DATABASE_URL",
        "CORS_ORIGINS",
    ]

    lines = [
        "# MedScan — local API keys (PRIVATE)",
        "",
        "> Auto-generated by `python scripts/sync_api_keys_doc.py`. Gitignored — do not commit.",
        "",
        f"**Last updated:** {date.today().isoformat()}",
        "",
        "---",
        "",
        "## Backend — `medscan/backend/.env`",
        "",
        "| Variable | Value |",
        "|----------|-------|",
    ]
    for k in backend_keys:
        if k == "MEDSCAN_CLIENT_API_KEYS" and not be.get(k):
            val = client
        else:
            val = be.get(k, "")
        lines.append(_row(k, val))

    lines += [
        "",
        "---",
        "",
        "## Frontend — `medscan/frontend/.env`",
        "",
        "| Variable | Value |",
        "|----------|-------|",
    ]
    for k in frontend_keys:
        val = fe.get(k, "")
        if k == "VITE_SUPABASE_URL" and not val:
            val = be.get("SUPABASE_URL", "")
        if k == "VITE_SUPABASE_ANON_KEY" and not val:
            val = be.get("SUPABASE_ANON_KEY", "")
        if k == "VITE_MEDSCAN_API_KEY" and not val:
            val = client
        lines.append(_row(k, val))

    api_url = fe.get("VITE_API_URL") or "https://medscan-api.azurewebsites.net"
    lines += [
        "",
        "---",
        "",
        "## Mobile — `flutter run` / `flutter build`",
        "",
        "| Dart define | Value |",
        "|-------------|-------|",
        _row("API_BASE_URL", api_url),
        _row("MEDSCAN_API_KEY", client),
        "",
        "---",
        "",
        "## Azure App Service — `medscan-api`",
        "",
        "| Setting | Value |",
        "|---------|-------|",
    ]
    for k in azure_keys:
        val = be.get(k, "")
        if k == "MEDSCAN_CLIENT_API_KEYS":
            val = client
        if k == "CORS_ORIGINS" and not val:
            val = "https://icy-pond-06a17d300.7.azurestaticapps.net"
        lines.append(_row(k, val))

    lines += [
        "",
        "---",
        "",
        "## GitHub Actions secrets",
        "",
        "| Secret | Value |",
        "|--------|-------|",
        "| `AZURE_CREDENTIALS` | _(paste from GitHub Secrets)_ |",
        "| `AZURE_SWA_DEPLOYMENT_TOKEN` | _(paste from GitHub Secrets)_ |",
        "",
    ]

    _DOC.parent.mkdir(parents=True, exist_ok=True)
    _DOC.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {_DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
